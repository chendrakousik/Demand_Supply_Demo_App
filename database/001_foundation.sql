CREATE OR REPLACE VIEW ANALYTICS.ALLOCATION_SUMMARY AS
WITH RUN_TOTALS AS (
    SELECT PAYLOAD:runId::VARCHAR AS RUN_ID,
           SUM(PAYLOAD:requested::NUMBER) AS REQUESTED,
           SUM(PAYLOAD:allocated::NUMBER) AS ALLOCATED,
           SUM(PAYLOAD:unfilled::NUMBER) AS UNFILLED
    FROM PLANNING.ALLOCATION_RESULTS GROUP BY 1
), SUPPLY_TOTALS AS (
    SELECT R.ID AS RUN_ID, SUM(S.VALUE:quantity::NUMBER) AS AVAILABLE
    FROM PLANNING.ALLOCATION_RUNS R, LATERAL FLATTEN(INPUT => R.PAYLOAD:supply) S
    WHERE R.PAYLOAD:status::VARCHAR = 'completed' GROUP BY 1
)
SELECT R.ID AS RUN_ID, COALESCE(T.REQUESTED, 0) AS REQUESTED,
       COALESCE(T.ALLOCATED, 0) AS ALLOCATED, COALESCE(T.UNFILLED, 0) AS UNFILLED,
       COALESCE(S.AVAILABLE, 0) AS AVAILABLE,
       DIV0(COALESCE(T.ALLOCATED, 0), COALESCE(T.REQUESTED, 0)) AS FULFILLMENT,
       DIV0(COALESCE(T.ALLOCATED, 0), COALESCE(S.AVAILABLE, 0)) AS UTILIZATION
FROM PLANNING.ALLOCATION_RUNS R
LEFT JOIN RUN_TOTALS T ON R.ID = T.RUN_ID
LEFT JOIN SUPPLY_TOTALS S ON R.ID = S.RUN_ID
WHERE R.PAYLOAD:status::VARCHAR = 'completed';

CREATE OR REPLACE VIEW ANALYTICS.SHORTAGE_BY_PRODUCT_CUSTOMER AS
SELECT PAYLOAD:runId::VARCHAR AS RUN_ID, PAYLOAD:productId::VARCHAR AS PRODUCT_ID,
       PAYLOAD:customerId::VARCHAR AS CUSTOMER_ID, SUM(PAYLOAD:quantity::NUMBER) AS SHORTAGE
FROM PLANNING.SHORTAGES GROUP BY 1, 2, 3;
